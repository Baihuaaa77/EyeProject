-- 第一版结构：PostgreSQL 与 H2（PostgreSQL 模式）通用写法。时间一律为 UTC 毫秒。

CREATE TABLE accounts (
    id            VARCHAR(36)  PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64),
    created_at    BIGINT       NOT NULL
);

-- 被测者：本人或家庭成员。只存出生年月。
CREATE TABLE subjects (
    id          VARCHAR(36) PRIMARY KEY,
    account_id  VARCHAR(36) NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    relation    VARCHAR(16) NOT NULL,
    nickname    VARCHAR(32) NOT NULL,
    birth_year  INT,
    birth_month INT,
    sex         VARCHAR(16),
    is_default  BOOLEAN     NOT NULL,
    created_at  BIGINT      NOT NULL
);
CREATE INDEX idx_subjects_account ON subjects (account_id);

-- 同意为追加式证据链：最新一条生效，撤回也是一条记录。
CREATE TABLE consents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     VARCHAR(36) NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    subject_id     VARCHAR(36) REFERENCES subjects (id) ON DELETE CASCADE,
    type           VARCHAR(32) NOT NULL,
    policy_version VARCHAR(32) NOT NULL,
    granted        BOOLEAN     NOT NULL,
    recorded_at    BIGINT      NOT NULL
);
CREATE INDEX idx_consents_account ON consents (account_id, type);

-- 测试记录不可变。摘要列明文便于查询；原文 AES-256-GCM 加密（key_id 便于轮换）。
CREATE TABLE records (
    id                 VARCHAR(36) PRIMARY KEY,
    account_id         VARCHAR(36) NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    subject_id         VARCHAR(36) NOT NULL REFERENCES subjects (id) ON DELETE CASCADE,
    kind               VARCHAR(16) NOT NULL,
    protocol_version   INT,
    assessment_version VARCHAR(64),
    risk_level         VARCHAR(16) NOT NULL,
    quality            VARCHAR(16) NOT NULL,
    tested_at          BIGINT      NOT NULL,
    uploaded_at        BIGINT      NOT NULL,
    payload_sha256     VARCHAR(64) NOT NULL,
    features_json      TEXT        NOT NULL,
    key_id             VARCHAR(32) NOT NULL,
    payload_cipher     BYTEA       NOT NULL,
    client_platform    VARCHAR(16),
    app_version        VARCHAR(32)
);
CREATE INDEX idx_records_subject_kind ON records (subject_id, kind, tested_at);
CREATE INDEX idx_records_account ON records (account_id, tested_at);

-- 不透明令牌只存 SHA-256；同一登录会话共享 family_id，刷新令牌被重用时整族吊销。
CREATE TABLE auth_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    account_id VARCHAR(36) NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    kind       VARCHAR(8)  NOT NULL,
    family_id  VARCHAR(36) NOT NULL,
    expires_at BIGINT      NOT NULL,
    revoked_at BIGINT,
    created_at BIGINT      NOT NULL
);
CREATE INDEX idx_tokens_family ON auth_tokens (family_id);
CREATE INDEX idx_tokens_expiry ON auth_tokens (expires_at);

-- 审计只追加，不含健康数据内容；不设外键，账号删除后仍保留。
CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          BIGINT      NOT NULL,
    actor       VARCHAR(36),
    action      VARCHAR(32) NOT NULL,
    target_type VARCHAR(16),
    target_id   VARCHAR(36),
    outcome     VARCHAR(16) NOT NULL,
    ip_hash     VARCHAR(64)
);
CREATE INDEX idx_audit_at ON audit_events (at);
CREATE INDEX idx_audit_actor ON audit_events (actor);
